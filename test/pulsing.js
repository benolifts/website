// ========================================================
// PULSE GENERATION
// ========================================================

function pulse(microsec, pwmMicrosec, motorFrequency = sineFreq) {

    let [mask1, mask2, mask3, mask] = [0];

    const pwmTime = Number(pwmMicrosec ?? microsec);

    const microsecMod = microsec % sineFreqTimeInt;
    const progress = microsecMod / sineFreqTime;

    // Swap one of the phases to change direction.
    if (sineFreq > 0) {
        Sine1 = sin(progress * tau);
        Sine2 = sin(progress * tau - offset120deg);
        Sine3 = sin(progress * tau - offset240deg);
    } else {
        Sine1 = sin(progress * tau - offset120deg);
        Sine2 = sin(progress * tau);
        Sine3 = sin(progress * tau - offset240deg);
    }


    switch (pulsingMethod) {

        // ------------------------------------------------
        // ASYNC
        // ------------------------------------------------

        // ------------------------------------------------
        // ASYNC
        // ------------------------------------------------

        case "ASYNC": {

            let curTime;
            let continuousCarrierPosition = null;

            if (
                oscillationFunction != null &&
                useContinuousCarrierPhase
            ) {

                // Get the requested instantaneous frequency.
                const requestedFrequency =
                Number(oscillationFunction(pwmTime, motorFrequency));

                const nextFrequency =
                Number.isFinite(requestedFrequency) &&
                requestedFrequency >= 0
                ? requestedFrequency
                : 0;

                // Advance carrier phase continuously.
                // Use the average of the previous and current
                // frequencies over the elapsed sample interval.
                if (
                    continuousCarrierLastTime === null ||
                    pwmTime < continuousCarrierLastTime
                ) {
                    continuousCarrierPhase = 0;

                } else {
                    const elapsed =
                    pwmTime - continuousCarrierLastTime;

                    const averageFrequency =
                    (
                        continuousCarrierLastFrequency +
                        nextFrequency
                    ) / 2;

                    continuousCarrierPhase +=
                    averageFrequency * elapsed / 1000000;

                    continuousCarrierPhase -=
                    floor(continuousCarrierPhase);
                }

                continuousCarrierLastTime = pwmTime;
                continuousCarrierLastFrequency = nextFrequency;

                // Update the reported carrier frequency without
                // resetting the accumulated carrier phase.
                applyCarrierFrequency(nextFrequency);

                continuousCarrierPosition =
                PWMfreq >= 1
                ? continuousCarrierPhase
                : 1;

            } else if (oscillationFunction != null) {

                // Existing cycle-based behaviour.
                // Retained for RANDOM and ASYNC-MUSIC.

                const cycleFinished =
                carrierCycleStart === null ||
                pwmTime < carrierCycleStart ||
                pwmTime - carrierCycleStart >= carrierCyclePeriod;

                if (cycleFinished) {

                    const nextFrequency =
                    oscillationFunction(pwmTime);

                    applyCarrierFrequency(nextFrequency);

                    carrierCycleStart = pwmTime;

                    carrierCyclePeriod = PWMfreqTime > 0
                    ? PWMfreqTime
                    : 1000000;
                }

                curTime = Math.max(
                    0,
                    pwmTime - carrierCycleStart
                );

            } else {

                // Original fixed-frequency ASYNC timing.
                curTime = PWMfreqTimeInt > 0
                ? pwmTime % PWMfreqTimeInt
                : 0;
            }


            percentageTime1 =
            abs(Sine1 * pulsingPower) * PWMfreqTime;

            percentageTime2 =
            abs(Sine2 * pulsingPower) * PWMfreqTime;

            percentageTime3 =
            abs(Sine3 * pulsingPower) * PWMfreqTime;


            mask1 = (Sine1 > 0 ? high1 : low1);
            mask2 = (Sine2 > 0 ? high2 : low2);
            mask3 = (Sine3 > 0 ? high3 : low3);


            if (continuousCarrierPosition !== null) {

                // Smooth carrier operation: compare duty fractions
                // directly against the continuous carrier phase.
                mask =
                (
                    continuousCarrierPosition <
                    abs(Sine1 * pulsingPower)
                    ? mask1 : 0) |

                    (
                        continuousCarrierPosition <
                        abs(Sine2 * pulsingPower)
                        ? mask2 : 0) |

                        (
                            continuousCarrierPosition <
                            abs(Sine3 * pulsingPower)
                            ? mask3 : 0);

            } else {

                // Original fixed and cycle-based pulse generation.
                mask =
                ((curTime < percentageTime1) ? mask1 : 0) |
                ((curTime < percentageTime2) ? mask2 : 0) |
                ((curTime < percentageTime3) ? mask3 : 0);
            }

            break;
        }


        // ------------------------------------------------
        // SYNC
        // ------------------------------------------------

        case "SYNC": {

            const triangleSync =
            abs((noOfSwitches * progress % 2) - 1);

            const pattern1 =
            Sine1 > 0 ? high1 : low1;

            const pattern2 =
            Sine2 > 0 ? high2 : low2;

            const pattern3 =
            Sine3 > 0 ? high3 : low3;


            mask1 =
            abs(Sine1 * pulsingPower) > triangleSync
            ? pattern1
            : 0;

            mask2 =
            abs(Sine2 * pulsingPower) > triangleSync
            ? pattern2
            : 0;

            mask3 =
            abs(Sine3 * pulsingPower) > triangleSync
            ? pattern3
            : 0;


            mask = mask1 | mask2 | mask3;

            break;
        }


        // ------------------------------------------------
        // SHE-PWM
        // ------------------------------------------------

        case "SHE-PWM": {

            if (pulsingPower <= 0) break;

            const currentSin1 = abs(Sine1);
            const currentSin2 = abs(Sine2);
            const currentSin3 = abs(Sine3);

            const pattern1 =
            Sine1 > 0 ? high1 : low1;

            const pattern2 =
            Sine2 > 0 ? high2 : low2;

            const pattern3 =
            Sine3 > 0 ? high3 : low3;


            for (let i = 0; i < pulsePattern; ++i) {
                if (pulseTimes[i] <= currentSin1) {
                    mask1 = (i & 1) ? 0 : pattern1;
                }
            }

            for (let i = 0; i < pulsePattern; ++i) {
                if (pulseTimes[i] <= currentSin2) {
                    mask2 = (i & 1) ? 0 : pattern2;
                }
            }

            for (let i = 0; i < pulsePattern; ++i) {
                if (pulseTimes[i] <= currentSin3) {
                    mask3 = (i & 1) ? 0 : pattern3;
                }
            }


            mask = mask1 | mask2 | mask3;

            break;
        }
    }


    registers = (~mask) & fullMask;
    registers = mask;

    return registers;
}
